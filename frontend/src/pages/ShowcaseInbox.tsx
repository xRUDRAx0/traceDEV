import React, { useEffect, useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { ArrowLeft, Mail, FileSpreadsheet, CheckCircle2 } from 'lucide-react';
import { API_URL } from '../config';

export default function ShowcaseInbox() {
  const navigate = useNavigate();
  const [emails, setEmails] = useState<any[]>([]);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    const fetchEmails = async () => {
      try {
        const res = await fetch(`${API_URL}/api/showcase/emails`);
        const data = await res.json();
        if (data.success && data.emails) {
          // reverse to show newest first
          setEmails(data.emails.reverse());
        }
      } catch (e) {
        console.error(e);
      } finally {
        setLoading(false);
      }
    };
    
    fetchEmails();
  }, []);

  return (
    <div className="max-w-4xl mx-auto space-y-8 animate-in fade-in duration-500 pb-16 pt-8">
      <div className="flex items-center gap-4 border-b border-border pb-6">
        <button onClick={() => navigate('/showcase')} className="p-2 hover:bg-surface-secondary rounded-full text-text-secondary transition-colors">
          <ArrowLeft className="w-5 h-5" />
        </button>
        <div>
          <div className="flex items-center gap-3">
             <h1 className="text-3xl font-black text-text-primary tracking-tight">Local Demo Inbox</h1>
             <span className="px-2.5 py-0.5 bg-success/20 text-success rounded uppercase tracking-widest text-[10px] font-bold border border-success/30 flex items-center gap-1">
                <CheckCircle2 className="w-3 h-3" /> VERIFIED DELIVERY
             </span>
          </div>
          <p className="mt-2 text-text-secondary font-medium">Emails generated by TRACE showcase workflows are stored here.</p>
        </div>
      </div>

      <div className="space-y-6">
        {loading ? (
          <div className="p-12 text-center text-text-muted">Loading inbox...</div>
        ) : emails.length === 0 ? (
          <div className="p-12 text-center text-text-muted bg-surface rounded-xl border border-border">
             <Mail className="w-12 h-12 mx-auto mb-4 opacity-20" />
             <p>No demo emails found.</p>
             <p className="text-sm mt-2">Run the Weekly Sales Report showcase to generate one.</p>
          </div>
        ) : (
          emails.map(email => (
            <div key={email.id} className="bg-surface border border-border rounded-xl shadow-sm overflow-hidden">
               <div className="p-4 bg-surface-secondary border-b border-border flex justify-between items-center">
                  <div className="flex items-center gap-3">
                    <div className="w-10 h-10 bg-accent/20 rounded-full flex items-center justify-center border border-accent/30">
                       <span className="text-accent font-bold">TR</span>
                    </div>
                    <div>
                       <p className="font-bold text-text-primary">{email.from}</p>
                       <p className="text-xs text-text-muted">to {email.to}</p>
                    </div>
                  </div>
                  <div className="text-xs text-text-muted font-medium">
                     {new Date(email.deliveredAt).toLocaleString()}
                  </div>
               </div>
               
               <div className="p-6 space-y-6">
                  <div>
                    <h3 className="font-bold text-lg text-text-primary mb-2">{email.subject}</h3>
                    <div className="inline-flex items-center gap-2 px-3 py-1.5 bg-background border border-border rounded-lg text-sm font-medium text-text-secondary cursor-pointer hover:bg-surface-secondary transition-colors">
                       <FileSpreadsheet className="w-4 h-4 text-accent" />
                       {email.attachment}
                    </div>
                  </div>
                  
                  <div className="whitespace-pre-line text-sm text-text-primary bg-background p-4 rounded-xl border border-border/50">
                    {email.body}
                  </div>
               </div>
            </div>
          ))
        )}
      </div>
    </div>
  );
}
